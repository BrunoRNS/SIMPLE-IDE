  private LocalCompletionProviders() {}

  public static CompletionProvider forSyntaxStyle(String syntaxStyle) {
    List<String> keywords = KEYWORDS.get(syntaxStyle);
    if (keywords == null) {
      return null;
    }
    DefaultCompletionProvider provider = new DefaultCompletionProvider();
    for (String keyword : keywords) {
      provider.addCompletion(new BasicCompletion(provider, keyword));
    }
    return provider;
  }

  public static boolean supports(String syntaxStyle) {
    return KEYWORDS.containsKey(syntaxStyle);
  }
